// Package wire renders TypeScript declarations of the JSON that Seaport's Go
// types put on the wire (the admin API's responses and the live events), by
// reflection: the real `json` tags, embedded structs, pointers, slices and
// maps are read from the types themselves, so a changed Go field changes the
// web's types at compile time.
//
// Reflection can't see what Go leaves out of a type: the names the web wants
// (a Spec says which Go type is which TypeScript name) and the values of the
// enum-like strings (a Spec names one constant of each const block; the block
// is read from the source). Doc comments come from the source too. Anything
// the renderer can't type exactly (an unnamed struct type, a string type that
// is not a registered enum, a custom marshaler) is an error, never a guess.
//
// The generator is internal/wire/gen (`go generate ./internal/wire`); seaport.go
// lists the types and the enums.
package wire

import (
	"encoding"
	"encoding/json"
	"fmt"
	"io/fs"
	"reflect"
	"regexp"
	"sort"
	"strings"
	"time"
)

// Field names a struct field by the Go type that declares it and its Go name.
type Field struct {
	Type reflect.Type
	Name string
}

// Enum is a TypeScript union of string literals.
type Enum struct {
	// Name is the TypeScript name.
	Name string
	// Type is the Go string type the enum is (nil: the fields that name the
	// enum in Spec.FieldEnums are plain strings in Go).
	Type reflect.Type
	// Pkg is the package of Anchor, relative to internal/ (when Type is nil).
	Pkg string
	// Anchor names one constant of the const block that lists the values:
	// every constant of that block is a value, in declaration order. A new
	// constant in the block reaches the web without touching the Spec.
	Anchor string
	// Also lists values the block doesn't ("" for "none"); they come first.
	Also []string
}

// Spec says what to render.
type Spec struct {
	// Module is the Go module path ("github.com/…/seaport"); the source of
	// a package is read from <repo>/<path under the module>.
	Module string
	// Generator is the program's path, for the header.
	Generator string
	// Preamble lines go after the header (imports of Raw types).
	Preamble []string
	// Types maps each TypeScript name to its Go type. Every named type the
	// renderer meets while walking fields must be here (or be time.Time, an
	// identity ID or an Enum): naming is deliberate, never derived.
	Types map[string]reflect.Type
	// Enums are the string unions.
	Enums []Enum
	// FieldEnums gives a plain Go string field an enum.
	FieldEnums map[Field]string
	// Raw overrides the TypeScript type of a field (not optional-ness).
	Raw map[Field]string
	// Events maps each live event type to its payload's Go type; rendered
	// as the interface WireEvents.
	Events map[string]reflect.Type
}

var (
	timeType        = reflect.TypeFor[time.Time]()
	rawMessageType  = reflect.TypeFor[json.RawMessage]()
	jsonMarshaler   = reflect.TypeFor[json.Marshaler]()
	textMarshaler   = reflect.TypeFor[encoding.TextMarshaler]()
	identifierRegex = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
)

// Render returns the TypeScript source of spec; repo is the repository root
// (the Go sources are read from it, for doc comments and enum values).
func Render(spec Spec, repo fs.FS) ([]byte, error) {
	r := &renderer{spec: spec, src: &sources{fsys: repo, module: spec.Module, pkgs: map[string]*pkgInfo{}},
		names: map[reflect.Type]string{}, enumByType: map[reflect.Type]string{}, enumNames: map[string]bool{}}
	return r.render()
}

type renderer struct {
	spec       Spec
	src        *sources
	names      map[reflect.Type]string // registered Go type → TypeScript name
	enumByType map[reflect.Type]string
	enumNames  map[string]bool
	trail      []string // where we are, for error messages
}

type member struct {
	name     string
	typ      string
	optional bool
	doc      string
}

func (r *renderer) render() ([]byte, error) {
	if err := r.index(); err != nil {
		return nil, err
	}
	var b strings.Builder
	gen := r.spec.Generator
	if gen == "" {
		gen = "internal/wire"
	}
	fmt.Fprintf(&b, "// Code generated by %s from the Go wire types; DO NOT EDIT.\n", gen)
	if len(r.spec.Preamble) > 0 {
		b.WriteString("\n")
		for _, line := range r.spec.Preamble {
			b.WriteString(line + "\n")
		}
	}
	b.WriteString("\n/** An identity (a UUID string). */\nexport type ID = string\n")

	enums := append([]Enum(nil), r.spec.Enums...)
	sort.Slice(enums, func(i, j int) bool { return enums[i].Name < enums[j].Name })
	for _, e := range enums {
		out, err := r.enum(e)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n" + out)
	}

	names := make([]string, 0, len(r.spec.Types))
	for name := range r.spec.Types {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		out, err := r.declaration(name, r.spec.Types[name])
		if err != nil {
			return nil, err
		}
		b.WriteString("\n" + out)
	}

	if len(r.spec.Events) > 0 {
		out, err := r.events()
		if err != nil {
			return nil, err
		}
		b.WriteString("\n" + out)
	}
	return []byte(b.String()), nil
}

// index checks the spec's names and builds the lookups.
func (r *renderer) index() error {
	for name, t := range r.spec.Types {
		if !identifierRegex.MatchString(name) || name == "ID" {
			return fmt.Errorf("wire: %q is not a usable TypeScript name", name)
		}
		if t == nil {
			return fmt.Errorf("wire: %s has no Go type", name)
		}
		if other, dup := r.names[t]; dup {
			return fmt.Errorf("wire: %s and %s are the same Go type (%s)", other, name, t)
		}
		r.names[t] = name
	}
	for _, e := range r.spec.Enums {
		if !identifierRegex.MatchString(e.Name) || e.Name == "ID" {
			return fmt.Errorf("wire: %q is not a usable TypeScript name", e.Name)
		}
		if _, clash := r.spec.Types[e.Name]; clash || r.enumNames[e.Name] {
			return fmt.Errorf("wire: the name %s is used twice", e.Name)
		}
		r.enumNames[e.Name] = true
		if e.Type != nil {
			if e.Type.Kind() != reflect.String || e.Type.PkgPath() == "" {
				return fmt.Errorf("wire: enum %s: %s is not a named string type", e.Name, e.Type)
			}
			if other, dup := r.enumByType[e.Type]; dup {
				return fmt.Errorf("wire: enums %s and %s are the same Go type", other, e.Name)
			}
			r.enumByType[e.Type] = e.Name
		}
	}
	for f, name := range r.spec.FieldEnums {
		if !r.enumNames[name] {
			return fmt.Errorf("wire: field %s.%s names the unknown enum %s", f.Type, f.Name, name)
		}
	}
	return nil
}

// enum renders one union.
func (r *renderer) enum(e Enum) (string, error) {
	var pkg, doc string
	if e.Type != nil {
		pkg = e.Type.PkgPath()
		d, err := r.src.typeDoc(pkg, e.Type.Name())
		if err != nil {
			return "", err
		}
		doc = retitle(d.doc, e.Type.Name(), e.Name)
	} else {
		if e.Pkg == "" {
			return "", fmt.Errorf("wire: enum %s needs a Type or a Pkg", e.Name)
		}
		pkg = r.spec.Module + "/internal/" + e.Pkg
	}
	values, err := r.src.constBlock(pkg, e.Anchor, e.Type)
	if err != nil {
		return "", fmt.Errorf("wire: enum %s: %w", e.Name, err)
	}
	values = append(append([]string(nil), e.Also...), values...)
	seen := map[string]bool{}
	lits := make([]string, 0, len(values))
	for _, v := range values {
		if seen[v] {
			return "", fmt.Errorf("wire: enum %s lists %q twice", e.Name, v)
		}
		seen[v] = true
		lits = append(lits, quote(v))
	}
	return docComment(doc, "") + union("export type "+e.Name+" =", lits) + "\n", nil
}

// union renders `head a | b`, one member per line when it doesn't fit.
func union(head string, members []string) string {
	one := head + " " + strings.Join(members, " | ")
	if len(one) <= 80 {
		return one
	}
	return head + "\n  | " + strings.Join(members, "\n  | ")
}

// declaration renders a registered type: an interface for a struct, else an alias.
func (r *renderer) declaration(name string, t reflect.Type) (string, error) {
	r.trail = []string{name}
	defer func() { r.trail = nil }()
	doc := ""
	if t.PkgPath() != "" {
		d, err := r.src.typeDoc(t.PkgPath(), t.Name())
		if err != nil {
			return "", err
		}
		doc = retitle(d.doc, t.Name(), name)
	}
	if t.Kind() != reflect.Struct {
		expr, err := r.expr(t, true)
		if err != nil {
			return "", err
		}
		return docComment(doc, "") + "export type " + name + " = " + expr + "\n", nil
	}
	members, err := r.members(t)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(docComment(doc, ""))
	b.WriteString("export interface " + name + " {\n")
	for _, m := range members {
		b.WriteString(docComment(m.doc, "  "))
		b.WriteString("  " + m.line() + "\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func (m member) line() string {
	name := m.name
	if !identifierRegex.MatchString(name) {
		name = quote(name)
	}
	if m.optional {
		name += "?"
	}
	return name + ": " + m.typ
}

// events renders WireEvents: the payload type of every live event type.
func (r *renderer) events() (string, error) {
	types := make([]string, 0, len(r.spec.Events))
	for typ := range r.spec.Events {
		types = append(types, typ)
	}
	sort.Strings(types)
	var b strings.Builder
	b.WriteString("/** The payload of every live event type (GET /api/v1/events), by type. */\nexport interface WireEvents {\n")
	for _, typ := range types {
		r.trail = []string{"event " + typ}
		expr, err := r.expr(r.spec.Events[typ], false)
		if err != nil {
			return "", err
		}
		b.WriteString("  " + quote(typ) + ": " + expr + "\n")
	}
	r.trail = nil
	b.WriteString("}\n")
	return b.String(), nil
}

// members lists the JSON members of struct type t, as encoding/json sees
// them: embedded structs are flattened, `json:"-"` and unexported fields are
// left out, an empty tag name is the Go name.
func (r *renderer) members(t reflect.Type) ([]member, error) {
	var out []member
	seen := map[string]string{}
	if err := r.collect(t, &out, seen); err != nil {
		return nil, err
	}
	return out, nil
}

func (r *renderer) collect(t reflect.Type, out *[]member, seen map[string]string) error {
	if t.Implements(jsonMarshaler) || reflect.PointerTo(t).Implements(jsonMarshaler) ||
		t.Implements(textMarshaler) || reflect.PointerTo(t).Implements(textMarshaler) {
		return r.errorf("%s has its own JSON encoding; render it by hand", t)
	}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if !f.IsExported() && !f.Anonymous {
			continue
		}
		omit := false
		for _, o := range strings.Split(opts, ",") {
			switch o {
			case "omitempty", "omitzero":
				omit = true
			case "string":
				return r.errorf("%s.%s: the json option `string` is not supported", t, f.Name)
			}
		}
		ft := f.Type
		if f.Anonymous && name == "" {
			et := ft
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				if err := r.collect(et, out, seen); err != nil {
					return err
				}
				continue
			}
		}
		if !f.IsExported() {
			continue
		}
		if name == "" {
			name = f.Name
		}
		if prev, dup := seen[name]; dup {
			return r.errorf("%s: the JSON name %q is used by %s and %s", t, name, prev, f.Name)
		}
		seen[name] = f.Name

		key := Field{Type: t, Name: f.Name}
		typ, err := r.fieldType(key, ft, omit)
		if err != nil {
			return err
		}
		doc, err := r.src.fieldDoc(t.PkgPath(), t.Name(), f.Name)
		if err != nil {
			return err
		}
		*out = append(*out, member{name: name, typ: typ, optional: omit, doc: doc})
	}
	return nil
}

// fieldType is the TypeScript type of one field: an override, else its Go type.
func (r *renderer) fieldType(key Field, ft reflect.Type, omit bool) (string, error) {
	r.trail = append(r.trail, key.Name)
	defer func() { r.trail = r.trail[:len(r.trail)-1] }()
	nullable := false
	if ft.Kind() == reflect.Pointer {
		ft = ft.Elem()
		nullable = !omit // an omitted nil pointer is absent, a kept one is null
	}
	var typ string
	switch raw, isRaw := r.spec.Raw[key]; {
	case isRaw:
		typ = raw
	case r.spec.FieldEnums[key] != "":
		if ft.Kind() != reflect.String {
			return "", r.errorf("%s.%s: enum %s on a non-string field", key.Type, key.Name, r.spec.FieldEnums[key])
		}
		typ = r.spec.FieldEnums[key]
	default:
		var err error
		if typ, err = r.expr(ft, false); err != nil {
			return "", err
		}
	}
	if nullable {
		typ += " | null"
	}
	return typ, nil
}

// expr is the TypeScript type of Go type t. top: t is the type of a
// declaration itself (a registered struct is expanded there, not named).
func (r *renderer) expr(t reflect.Type, top bool) (string, error) {
	switch {
	case t == timeType:
		return "string", nil
	case t == rawMessageType:
		return "unknown", nil
	case isID(t):
		return "ID", nil
	}
	if name, ok := r.enumByType[t]; ok {
		return name, nil
	}
	if name, ok := r.names[t]; ok && !top {
		return name, nil
	}
	if t.PkgPath() != "" && t.Name() != "" {
		// A named type: only the kinds below are understood.
		if t.Kind() == reflect.String {
			return "", r.errorf("%s is a named string type with no enum: add it to Spec.Enums", t)
		}
		if t.Kind() == reflect.Struct && !top {
			return "", r.errorf("%s has no TypeScript name: add it to Spec.Types", t)
		}
		if t.Implements(jsonMarshaler) || reflect.PointerTo(t).Implements(jsonMarshaler) ||
			t.Implements(textMarshaler) || reflect.PointerTo(t).Implements(textMarshaler) {
			return "", r.errorf("%s has its own JSON encoding; render it by hand", t)
		}
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Pointer:
		inner, err := r.expr(t.Elem(), false)
		if err != nil {
			return "", err
		}
		return inner + " | null", nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 && t.Kind() == reflect.Slice {
			return "string", nil // []byte is base64
		}
		inner, err := r.expr(t.Elem(), false)
		if err != nil {
			return "", err
		}
		return paren(inner) + "[]", nil
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", r.errorf("%s: only maps with string keys are supported", t)
		}
		inner, err := r.expr(t.Elem(), false)
		if err != nil {
			return "", err
		}
		return "Record<string, " + inner + ">", nil
	case reflect.Struct:
		if t.Name() != "" && t.PkgPath() != "" && !top {
			return "", r.errorf("%s has no TypeScript name: add it to Spec.Types", t)
		}
		members, err := r.members(t)
		if err != nil {
			return "", err
		}
		parts := make([]string, len(members))
		for i, m := range members {
			parts[i] = m.line()
		}
		if len(parts) == 0 {
			return "Record<string, never>", nil
		}
		return "{ " + strings.Join(parts, "; ") + " }", nil
	}
	return "", r.errorf("%s (%s) has no TypeScript equivalent", t, t.Kind())
}

func (r *renderer) errorf(format string, args ...any) error {
	return fmt.Errorf("wire: %s (at %s)", fmt.Sprintf(format, args...), strings.Join(r.trail, "."))
}

// isID: identity.ID[T], whatever T is.
func isID(t reflect.Type) bool {
	return strings.HasSuffix(t.PkgPath(), "/internal/identity") && strings.HasPrefix(t.Name(), "ID[")
}

// paren wraps a union so a following [] applies to all of it.
func paren(s string) string {
	if strings.ContainsAny(s, "|") {
		return "(" + s + ")"
	}
	return s
}

func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// retitle swaps a doc comment's leading Go name for the TypeScript name
// ("Agent is …" documents LibraryAgent as "LibraryAgent is …").
func retitle(doc, goName, tsName string) string {
	if goName != tsName && strings.HasPrefix(doc, goName+" ") {
		return tsName + doc[len(goName):]
	}
	return doc
}

// docComment renders text as a /** */ comment indented by indent ("" for none).
func docComment(text, indent string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return ""
	}
	text = strings.ReplaceAll(text, "*/", "*\\/")
	lines := strings.Split(text, "\n")
	if len(lines) == 1 {
		return indent + "/** " + lines[0] + " */\n"
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			b.WriteString(indent + " *\n")
			continue
		}
		b.WriteString(indent + " * " + l + "\n")
	}
	b.WriteString(indent + " */\n")
	return b.String()
}
